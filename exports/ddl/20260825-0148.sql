    PROCEDURE place_asset(
        p_tenant_code IN VARCHAR2,
        p_asset_id IN NUMBER,
        p_location_id IN NUMBER,
        p_source_type IN VARCHAR2 DEFAULT 'CORRECTION',
        p_source_id IN NUMBER DEFAULT NULL,
        p_notes IN VARCHAR2 DEFAULT NULL
    ) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM asset
         WHERE id = p_asset_id
           AND tenant_code = p_tenant_code;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20101, 'Bem inexistente no tenant informado.');
        END IF;

        SELECT COUNT(*) INTO v_count
          FROM asset_location
         WHERE id = p_location_id
           AND tenant_code = p_tenant_code
           AND active = 1;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20102, 'Local inexistente ou inativo no tenant informado.');
        END IF;

        UPDATE asset_location_history
           SET ended_at = SYSTIMESTAMP
         WHERE tenant_code = p_tenant_code
           AND asset_id = p_asset_id
           AND ended_at IS NULL;

        INSERT INTO asset_location_history (
            tenant_code, asset_id, location_id, started_at,
            source_type, source_id, notes
        ) VALUES (
            p_tenant_code, p_asset_id, p_location_id, SYSTIMESTAMP,
            p_source_type, p_source_id, p_notes
        );

        UPDATE asset
           SET current_location_id = p_location_id,
               updated_by = 'asset_ops_pkg.place_asset'
         WHERE id = p_asset_id
           AND tenant_code = p_tenant_code;

        INSERT INTO asset_event (
            tenant_code, asset_id, event_type, source_type, source_id, description, created_by
        ) VALUES (
            p_tenant_code, p_asset_id, 'LOCATION_CHANGED', p_source_type, p_source_id,
            'Localização patrimonial atualizada.', 'asset_ops_pkg.place_asset'
        );
    END place_asset;

    PROCEDURE assign_custody(
        p_tenant_code IN VARCHAR2,
        p_asset_id IN NUMBER,
        p_party_id IN NUMBER,
        p_custody_type IN VARCHAR2 DEFAULT 'RESPONSIBLE',
        p_term_reference IN VARCHAR2 DEFAULT NULL,
        p_notes IN VARCHAR2 DEFAULT NULL
    ) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM asset
         WHERE id = p_asset_id
           AND tenant_code = p_tenant_code;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20111, 'Bem inexistente no tenant informado.');
        END IF;

        SELECT COUNT(*) INTO v_count
          FROM asset_party
         WHERE id = p_party_id
           AND tenant_code = p_tenant_code
           AND active = 1;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20112, 'Responsável inexistente ou inativo no tenant informado.');
        END IF;

        UPDATE asset_custody
           SET ended_at = SYSTIMESTAMP,
               status = 'CLOSED'
         WHERE tenant_code = p_tenant_code
           AND asset_id = p_asset_id
           AND status = 'ACTIVE'
           AND ended_at IS NULL;

        INSERT INTO asset_custody (
            tenant_code, asset_id, party_id, custody_type,
            started_at, status, term_reference, notes
        ) VALUES (
            p_tenant_code, p_asset_id, p_party_id, p_custody_type,
            SYSTIMESTAMP, 'ACTIVE', p_term_reference, p_notes
        );

        UPDATE asset
           SET current_custodian_party_id = p_party_id,
               updated_by = 'asset_ops_pkg.assign_custody'
         WHERE id = p_asset_id
           AND tenant_code = p_tenant_code;

        INSERT INTO asset_event (
            tenant_code, asset_id, event_type, source_type, description, created_by
        ) VALUES (
            p_tenant_code, p_asset_id, 'CUSTODY_CHANGED', 'CUSTODY',
            'Responsabilidade patrimonial atualizada.', 'asset_ops_pkg.assign_custody'
        );
    END assign_custody;

    PROCEDURE execute_movement(
        p_tenant_code IN VARCHAR2,
        p_movement_id IN NUMBER,
        p_actor_party_id IN NUMBER
    ) IS
        v_move asset_movement%ROWTYPE;
    BEGIN
        SELECT * INTO v_move
          FROM asset_movement
         WHERE id = p_movement_id
           AND tenant_code = p_tenant_code
         FOR UPDATE;

        IF v_move.status <> 'APPROVED' THEN
            RAISE_APPLICATION_ERROR(-20121, 'Somente movimentação aprovada pode ser executada.');
        END IF;

        FOR r IN (
            SELECT *
              FROM asset_movement_item
             WHERE movement_id = p_movement_id
               AND tenant_code = p_tenant_code
               AND item_status = 'PENDING'
             ORDER BY id
        ) LOOP
            IF v_move.destination_location_id IS NOT NULL THEN
                place_asset(
                    p_tenant_code => p_tenant_code,
                    p_asset_id => r.asset_id,
                    p_location_id => v_move.destination_location_id,
                    p_source_type => 'MOVEMENT',
                    p_source_id => p_movement_id,
                    p_notes => v_move.reason
                );
            END IF;

            IF v_move.destination_party_id IS NOT NULL THEN
                assign_custody(
                    p_tenant_code => p_tenant_code,
                    p_asset_id => r.asset_id,
                    p_party_id => v_move.destination_party_id,
                    p_custody_type => CASE WHEN v_move.movement_type = 'LOAN_OUT' THEN 'LOANED_OUT' ELSE 'RESPONSIBLE' END,
                    p_term_reference => v_move.movement_code,
                    p_notes => v_move.reason
                );
            END IF;

            IF v_move.movement_type = 'LOAN_OUT' THEN
                UPDATE asset SET lifecycle_status = 'ON_LOAN', updated_by = 'asset_ops_pkg.execute_movement'
                 WHERE id = r.asset_id AND tenant_code = p_tenant_code;
            ELSIF v_move.movement_type = 'RETURN' THEN
                UPDATE asset SET lifecycle_status = 'ACTIVE', updated_by = 'asset_ops_pkg.execute_movement'
                 WHERE id = r.asset_id AND tenant_code = p_tenant_code;
            ELSIF v_move.movement_type = 'MAINTENANCE_DISPATCH' THEN
                UPDATE asset SET lifecycle_status = 'IN_MAINTENANCE', updated_by = 'asset_ops_pkg.execute_movement'
                 WHERE id = r.asset_id AND tenant_code = p_tenant_code;
            ELSIF v_move.movement_type = 'MAINTENANCE_RETURN' THEN
                UPDATE asset SET lifecycle_status = 'ACTIVE', updated_by = 'asset_ops_pkg.execute_movement'
                 WHERE id = r.asset_id AND tenant_code = p_tenant_code;
            END IF;

            UPDATE asset_movement_item
               SET item_status = 'EXECUTED'
             WHERE id = r.id;
        END LOOP;

        UPDATE asset_movement
           SET status = 'EXECUTED',
               executed_at = SYSTIMESTAMP,
               approved_by_party_id = NVL(approved_by_party_id, p_actor_party_id)
         WHERE id = p_movement_id
           AND tenant_code = p_tenant_code;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20122, 'Movimentação inexistente no tenant informado.');
    END execute_movement;

    PROCEDURE scan_inventory(
        p_tenant_code IN VARCHAR2,
        p_inventory_id IN NUMBER,
        p_asset_id IN NUMBER,
        p_found_location_id IN NUMBER,
        p_found_party_id IN NUMBER,
        p_condition_found IN VARCHAR2,
        p_scanned_by_party_id IN NUMBER,
        p_notes IN VARCHAR2 DEFAULT NULL
    ) IS
        v_expected_location NUMBER;
        v_expected_party NUMBER;
        v_status VARCHAR2(40);
    BEGIN
        SELECT current_location_id, current_custodian_party_id
          INTO v_expected_location, v_expected_party
          FROM asset
         WHERE id = p_asset_id
           AND tenant_code = p_tenant_code;

        IF p_condition_found = 'DAMAGED' OR p_condition_found = 'UNUSABLE' THEN
            v_status := 'DAMAGED';
        ELSIF NVL(v_expected_location, -1) <> NVL(p_found_location_id, -1) THEN
            v_status := 'DIVERGENT_LOCATION';
        ELSIF NVL(v_expected_party, -1) <> NVL(p_found_party_id, -1) THEN
            v_status := 'DIVERGENT_CUSTODIAN';
        ELSE
            v_status := 'FOUND';
        END IF;

        MERGE INTO asset_inventory_item t
        USING (
            SELECT p_tenant_code tenant_code,
                   p_inventory_id inventory_id,
                   p_asset_id asset_id
              FROM dual
        ) s
        ON (t.tenant_code = s.tenant_code AND t.inventory_id = s.inventory_id AND t.asset_id = s.asset_id)
        WHEN MATCHED THEN UPDATE SET
            t.expected_location_id = v_expected_location,
            t.found_location_id = p_found_location_id,
            t.expected_party_id = v_expected_party,
            t.found_party_id = p_found_party_id,
            t.scan_status = v_status,
            t.condition_found = p_condition_found,
            t.scanned_at = SYSTIMESTAMP,
            t.scanned_by_party_id = p_scanned_by_party_id,
            t.notes = p_notes
        WHEN NOT MATCHED THEN INSERT (
            tenant_code, inventory_id, asset_id,
            expected_location_id, found_location_id,
            expected_party_id, found_party_id,
            scan_status, condition_found, scanned_at,
            scanned_by_party_id, notes
        ) VALUES (
            p_tenant_code, p_inventory_id, p_asset_id,
            v_expected_location, p_found_location_id,
            v_expected_party, p_found_party_id,
            v_status, p_condition_found, SYSTIMESTAMP,
            p_scanned_by_party_id, p_notes
        );
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20131, 'Bem inexistente no tenant informado.');
    END scan_inventory;

    PROCEDURE execute_write_off(
        p_tenant_code IN VARCHAR2,
        p_write_off_id IN NUMBER,
        p_actor_party_id IN NUMBER
    ) IS
        v_asset_id NUMBER;
        v_status VARCHAR2(30);
    BEGIN
        SELECT asset_id, status
          INTO v_asset_id, v_status
          FROM asset_write_off
         WHERE id = p_write_off_id
           AND tenant_code = p_tenant_code
         FOR UPDATE;

        IF v_status <> 'APPROVED' THEN
            RAISE_APPLICATION_ERROR(-20141, 'Baixa ainda não aprovada.');
        END IF;

        UPDATE asset
           SET lifecycle_status = 'WRITTEN_OFF',
               status_reason = 'Baixa patrimonial aprovada e executada.',
               written_off_at = SYSTIMESTAMP,
               updated_by = 'asset_ops_pkg.execute_write_off'
         WHERE id = v_asset_id
           AND tenant_code = p_tenant_code;

        UPDATE asset_custody
           SET ended_at = SYSTIMESTAMP,
               status = 'CLOSED'
         WHERE tenant_code = p_tenant_code
           AND asset_id = v_asset_id
           AND status = 'ACTIVE'
           AND ended_at IS NULL;

        UPDATE asset_location_history
           SET ended_at = SYSTIMESTAMP
         WHERE tenant_code = p_tenant_code
           AND asset_id = v_asset_id
           AND ended_at IS NULL;

        UPDATE asset_write_off
           SET status = 'EXECUTED',
               executed_at = SYSTIMESTAMP,
               executed_by_party_id = p_actor_party_id
         WHERE id = p_write_off_id
           AND tenant_code = p_tenant_code;

        INSERT INTO asset_event (
            tenant_code, asset_id, event_type, source_type, source_id, description, created_by
        ) VALUES (
            p_tenant_code, v_asset_id, 'WRITE_OFF_EXECUTED', 'WRITE_OFF', p_write_off_id,
            'Baixa patrimonial executada.', 'asset_ops_pkg.execute_write_off'
        );
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20142, 'Baixa inexistente no tenant informado.');
    END execute_write_off;

END asset_ops_pkg;
