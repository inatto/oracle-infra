create trigger TRG_TENANT_GOVERNANCE_BIU
    before insert or update
    on TENANT_GOVERNANCE
    for each row
BEGIN
    :new.tenant_code :=
            LOWER(TRIM(:new.tenant_code));

    :new.page_code :=
            LOWER(TRIM(:new.page_code));

    :new.section_code :=
            LOWER(TRIM(:new.section_code));

    IF :new.member_type IS NOT NULL THEN
        :new.member_type :=
                TRIM(:new.member_type);
    END IF;

    IF :new.uf_code IS NOT NULL THEN
        :new.uf_code :=
                UPPER(TRIM(:new.uf_code));
    END IF;

    IF INSERTING THEN
        :new.created_at :=
                NVL(:new.created_at, SYSDATE);

        :new.section_sort_order :=
                NVL(:new.section_sort_order, 0);

        :new.sort_order :=
                NVL(:new.sort_order, 0);

        :new.active :=
                NVL(:new.active, 1);
    ELSE
        :new.updated_at := SYSDATE;
    END IF;
END;
